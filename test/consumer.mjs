import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { Canvas } from "@frankfmy/canvas-geometry";
import { UB } from "@frankfmy/canvas-geometry/bounds";
import { Camera } from "@frankfmy/canvas-geometry/camera";
import { Convex } from "@frankfmy/canvas-geometry/convex";
import { UC2 } from "@frankfmy/canvas-geometry/coords";
import { UD } from "@frankfmy/canvas-geometry/depth";
import { Draw } from "@frankfmy/canvas-geometry/draw";
import { UE } from "@frankfmy/canvas-geometry/edge";
import { UG } from "@frankfmy/canvas-geometry/geom";
import { UL } from "@frankfmy/canvas-geometry/line";
import { UPL } from "@frankfmy/canvas-geometry/polyline";
import { Render } from "@frankfmy/canvas-geometry/render";
import { ServerRender } from "@frankfmy/canvas-geometry/server/render";
import { US } from "@frankfmy/canvas-geometry/size";
import { Spatial } from "@frankfmy/canvas-geometry/spatial";
assert.equal(typeof globalThis.window, "undefined");
assert.equal(typeof Canvas, "function"); assert.equal(typeof Draw, "function");
const specifiers = JSON.parse(readFileSync(new URL("./consumer-exports.json", import.meta.url), "utf8"));
for (const specifier of specifiers) await import(specifier);
assert.deepEqual(UC2.sum({ x: 2, y: 3 }, { x: 5, y: 7 }), { x: 7, y: 10 });
const bounds = { minX: 0, minY: 0, maxX: 10, maxY: 10 };
assert.equal(UB.has(bounds, { x: 5, y: 5 }), true);
assert.equal(UB.has(bounds, { x: 0, y: 5 }), false);
assert.equal(UB.at(bounds, { x: 0, y: 5 }), true);
const polygon = UG.convex(bounds);
assert.deepEqual(Convex.bound(polygon), bounds);
assert.equal(Convex.has(polygon, { x: 5, y: 5 }), true);
assert.equal(Convex.has(polygon, { x: 0, y: 5 }), false);
const copied = Convex.copy(polygon); copied[0].x = 50; assert.notDeepEqual(copied, polygon);
assert.equal(UPL.length([{ x: 0, y: 0 }, { x: 3, y: 4 }]), 5);
assert.equal(UD.has([1, 0]), false); assert.equal(UD.at([1, 0]), true);
const a = [{ x: 0, y: 0 }, { x: 10, y: 10 }], b = [{ x: 0, y: 10 }, { x: 10, y: 0 }];
assert.deepEqual(UE.joint(a, b), { x: 5, y: 5 });
assert.deepEqual(UL.joint({ type: "line", points: a }, { type: "line", points: b }), { x: 5, y: 5 });
assert.deepEqual(US.center({ w: 100, h: 40 }), { x: 50, y: 20 });
let frames = 0, draws = 0;
const render = new ServerRender({ draw: () => draws++ });
render.push({ id: "owned", func: () => ++frames < 3 }); render.settle();
assert.equal(frames, 3); assert.equal(draws, 3);
const camera = new Camera(Camera.zero(), { id: "camera", render });
camera.mutate({ center: { x: 30, y: -12 }, scale: 2 }); render.settle();
assert.ok(Camera.eq(camera.state, camera.target));
const point = { x: 8, y: 9 }, anchor = { x: 50, y: 20 };
assert.deepEqual(Camera.refract(camera.state, anchor, Camera.unrefract(camera.state, anchor, point)), point);
assert.ok(Render.alpha(16, 90) > 0 && Render.alpha(16, 90) < 1);
const spatial = new Spatial(16), owned = { id: "owned", bounds: { ...bounds } };
spatial.upsert(owned, { id: "virtual", point: { x: 5, y: 5 }, virtual: true });
owned.bounds.minX = 500;
assert.deepEqual([...spatial.ray({ x: 5, y: 5 })], ["owned"]);
assert.deepEqual([...spatial.query(bounds, { includeVirtual: true })].sort(), ["owned", "virtual"]);
const mounts = [], exits = [], view = spatial.slice(bounds, { onmount: id => mounts.push(id), onfrustum: id => exits.push(id) });
assert.deepEqual([...view.items].sort(), ["owned", "virtual"]);
spatial.delete("owned"); assert.ok(exits.includes("owned")); assert.equal(spatial.ray({ x: 5, y: 5 }).size, 0);
assert.throws(() => new Spatial(0), RangeError);
assert.throws(() => spatial.upsert({ id: "unsafe", point: { x: Infinity, y: 0 } }), RangeError);
view.destroy(); spatial.destroy(); camera.stop(); render.clear(); render.step();
assert.equal(spatial.query(bounds).size, 0);
const migrated = new Spatial(128);
migrated.upsert({ id: "cross-cell", point: { x: 127.9999, y: 1 } });
migrated.upsert({ id: "cross-cell", point: { x: 128.0001, y: 1 } });
assert.deepEqual([...migrated.ray({ x: 128.0001, y: 1 })], ["cross-cell"]);
const capsule = Convex.create([{ x: 0, y: 0 }, { x: 10, y: 0 }], 2);
assert.deepEqual(capsule.at(-1), capsule[0]);
assert.equal(UG.has(capsule, { x: 5, y: 0 }), true);
migrated.upsert({ id: "capsule", convex: capsule });
assert.ok(migrated.ray({ x: 5, y: 0 }).has("capsule"));
const mixed = new Spatial(16);
mixed.upsert({ id: "diagonal", polyline: [{ x: 0, y: 0 }, { x: 10, y: 10 }] }, { id: "singleton", polyline: [{ x: 5, y: 5 }] });
assert.deepEqual([...mixed.query(bounds)].sort(), ["diagonal", "singleton"]);
const other = UG.convex({ minX: 8, minY: 0, maxX: 18, maxY: 10 });
const translation = Convex.mtv(polygon, other);
assert.ok(translation);
assert.equal(Convex.collision(polygon.map(p => UC2.sum(p, translation)), other), false);
const contained = UG.convex({ minX: 4, minY: 4, maxX: 6, maxY: 6 });
const escape = Convex.mtv(contained, polygon);
assert.ok(escape);
assert.equal(Convex.collision(contained.map(p => UC2.sum(p, escape)), polygon), false);
const openQuery = [{ x: 0, y: 0 }, { x: 10, y: 0 }, { x: 10, y: 10 }];
const indexed = { id: "p", point: { x: 5, y: 0 } }, stable = new Spatial();
stable.upsert(indexed);
const frustums = [], sliced = stable.slice(openQuery, { onfrustum: id => frustums.push(id) });
assert.deepEqual([...sliced.items], ["p"]);
stable.upsert(indexed);
assert.deepEqual([...sliced.items], [...stable.query(openQuery)]);
assert.deepEqual([...sliced.items], ["p"]);
assert.deepEqual(frustums, []);
sliced.destroy(); stable.destroy();
const adjacent = new Spatial(128), near = { id: "near", point: { x: 127.9999, y: 1 } };
const nearQuery = { x: 128, y: 1 }, nearEvents = [];
const nearSlice = adjacent.slice(nearQuery, { onmount: id => nearEvents.push(`mount:${id}`), onfrustum: id => nearEvents.push(`frustum:${id}`) });
adjacent.upsert(near);
for (let repeat = 0; repeat < 3; repeat++) {
  assert.deepEqual([...adjacent.query(nearQuery)], ["near"]);
  assert.deepEqual([...adjacent.ray(nearQuery)], ["near"]);
  nearSlice.relocate(nearQuery); adjacent.upsert(near);
  assert.deepEqual([...nearSlice.items], ["near"]);
}
assert.deepEqual(nearEvents, ["mount:near"]);
assert.equal(adjacent.query({ x: 128.01, y: 1 }).size, 0);
nearSlice.destroy(); adjacent.destroy();
migrated.destroy(); mixed.destroy();
console.log(`installed pure geometry/SSR/manual render/spatial behavior: PASS (${specifiers.length} exports)`);
