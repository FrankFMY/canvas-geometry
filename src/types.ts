/**
 * Линия между двумя точками. В зависимости от {@link mode} интерпретируется как отрезок, луч или бесконечная прямая:
 *
 * - `"segment"` (по умолчанию, если `mode` не задан) — конечный отрезок между `points[0]` и `points[1]`;
 * - `"ray"` — луч из `points[0]` в направлении `points[1]`;
 * - `"infinity"` — бесконечная прямая через обе точки.
 *
 * Канон владения: точки **строго** между концами (концы не входят, касание концами не даёт коллизии).
 * Для `mode = "ray"`/`"infinity"` принадлежность определяется в `UL.shallow` с учётом направления.
 */
export interface Line {
	type: "line";
	points: [C2, C2];
	mode?: "infinity" | "ray";
}

/**
 * Кубическая кривая Безье по 4 контрольным точкам:
 * `[P0, P1, P2, P3]`: P0/P3 — концы, P1/P2 — направляющие.
 */
export interface Bezier {
	type: "bezier";
	points: [C2, C2, C2, C2];
}

/**
 * Сегмент кривой: {@link Line} или {@link Bezier}.
 */
export type CurveSegment = Line | Bezier;

/**
 * Составная кривая: массив сегментов.
 *
 * Сегменты рисуются/обрабатываются последовательно;
 * не предполагается замкнутость (для замкнутых контуров добавляйте явный замыкающий сегмент).
 */
export type Curve = CurveSegment[];
