/**
 * Точка в канонической форме {@link Convex}: одноэлементный массив.
 *
 * Эквивалент {@link C2}, обёрнутый для совместимости с `Convex`-API.
 */
export type Point = [C2];

/**
 * Ребро: пара точек `[start, end]`. Порядок значим для `eq`/`assign` и для некоторых предикатов.
 */
export type Edge = [C2, C2];

/**
 * Полигон как массив вершин (Y-вверх, CCW, **с замыкающей дублирующей вершиной**: первая === последней).
 *
 * Канон порядка: отличает {@link Polyline} (открытая ломаная, без замыкания) от {@link Convex} (замкнутый полигон)
 * по порогу `length > 3 && eq(g[0], g[n-1])` — минимум 3 уникальные вершины + закрывающий дубль первой.
 * Массивы `length <= 3` трактовуются как {@link Polyline} (точка/ребро/ломаная из 2 сегментов).
 *
 * Канон вырожденности:
 * 1 вершина (или все совпадают) → точка;
 * 2+ коллинеарных с разнесёнными концами → линия (концы — наиболее удалённые);
 * 3+ не на одной прямой → полигон.
 *
 * Пустой массив трактуется контекстно (см. JSDoc конкретных методов): `center` → `{0,0}`, `collision` → `false`, `edges` → `[]`.
 *
 * Канон владения: **строго** внутренние точки (рёбра/вершины не входят).
 * Канон контура: рёбра + вершины (включаются в `at`/`collision` containment).
 */
export type Convex = C2[];

/**
 * Открытая ломаная как массив вершин (Y-вверх) — обобщение {@link Edge} на случай изломов.
 *
 * Канон порядка: без замыкающей дублирующей вершины (отличие от {@link Convex}); крайние концы `g[0]` и `g[n-1]` —
 * «закрывающие точки» (концы ломаной). Иерархия примитивов: `C2` → `Edge` → `Polyline` → `Convex` → `Bounds`.
 *
 * Канон вырожденности:
 * 0 вершин → `empty`;
 * 1 вершина (или все совпадают) → точка;
 * 2+ коллинеарных с разнесёнными концами → ребро (концы — наиболее удалённые);
 * 2+ не на одной прямой → ломаная.
 *
 * Канон владения: 1D-interior = объединение открытых сегментов `(g[i], g[i+1])` для `i < n-1`
 * ∪ внутренних вершин `g[1..n-2]`; крайние концы `g[0]`/`g[n-1]` **исключены**.
 * Канон контура: замкнутые сегменты `[g[i], g[i+1]]` + все вершины (включая крайние) — включаются в `at`.
 *
 * Пустой массив трактуется контекстно (см. JSDoc методов): `center` → `{0,0}`, `has`/`collision` → `false`.
 */
export type Polyline = C2[];

/**
 * Универсальная геометрия:
 * - точка ({@link C2})
 * - прямоугольник ({@link Bounds})
 * - выпуклый полигон ({@link Convex})
 * - открытая ломаная ({@link Polyline}).
 *
 * Используется как параметр полиморфного API {@link UG} (см. `geom.ts`) и в {@link Spatial}/{@link SpatialView}
 * для передачи геометрии без оборачивания в {@link SpatialItem}. Дискриминация структурная:
 * `Bounds` — объект с `minX`; массив с `length > 3 && eq(g[0], g[n-1])` — `Convex` (замкнутый);
 * прочий массив — `Polyline`; `C2` — объект без `minX`.
 */
export type Geom = C2 | Bounds | Convex | Polyline;

/**
 * Нормированная глубина точки относительно фигуры по двум осям.
 *
 * Канон: 0 = центр фигуры, ±1 = контур, |val| > 1 — снаружи по этой оси.
 * `Infinity` — ось вырождена (фигура не имеет протяжённости по ней) и точка не совпадает с фигурой по этой оси; `0` — ось вырождена и точка совпадает.
 *
 * Для Size/Bounds — две независимые оси (X, Y).
 * Для линии — обе компоненты одинаковые (одна ось).
 * Для точки — `[0, 0]` (совпадение) или `[Infinity, Infinity]`.
 */
export type Depth = [number, number];

