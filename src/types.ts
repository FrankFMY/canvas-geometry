/**
 * Точка на 2D-плоскости. Базовый примитив: владеет самой собой (по канону владения).
 */
export interface C2 {
	x: number;
	y: number;
}

/**
 * Размер (ширина × высота) без позиции. Частный случай {@link Bounds} с неявной позицией в `{0, 0}` (minX/Y = 0,0).
 *
 * Допускает отрицательные значения (пакет их не запрещает), но в `isEmpty` и арифметике `w <= 0` / `h <= 0` считается пустым.
 */
export interface S2 {
	w: number;
	h: number;
}

/**
 * Осе-выровненный прямоугольник (AABB) по 4 границам.
 *
 * Канон вырожденности: все `min == max` → точка; одна ось вырождена → линия; обе с протяжённостью → полигон.
 * Канон владения: **строго** внутренние точки (рёбра и вершины не входят).
 * Канон контура: рёбра + вершины (включаются в `at`/`intersect`).
 *
 * Пакет не предназначен для «вывернутых» Bounds (min > max по оси) — методы предикатов/геометрии предполагают нормализованный порядок.
 */
export interface Bounds {
	minX: number;
	minY: number;
	maxX: number;
	maxY: number;
}

/**
 * Камера для проецирования мировых координат на экран.
 * `scale > 0`, при `scale = 1` — масштаб 1:1. Чем меньше, тем ближе
 */
export interface Camera {
	center: C2;
	scale: number;
}

